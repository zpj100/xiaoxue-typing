const used = new Set<string>()
export const chineseHanzi: LessonItem[] = []
export const chineseWrite: LessonItem[] = []

hanziBank.forEach(([char, pinyin, hint, grade], i) => {
  const key = `${grade}-${char}-${i}`
  if (used.has(key)) return
  used.add(key)
  const item: LessonItem = {
    id: `hz-${grade}-${i + 1}`,
    subject: 'chinese',
    grade,
    kind: 'hanzi',
    title: char,
    prompt: char,
    answer: pinyin,
    phonetic: pinyin,
    hint,
    strokes: hint,
  }
  chineseHanzi.push(item)
  chineseWrite.push({
    ...item,
    id: `wr-${grade}-${i + 1}`,
    kind: 'write',
    prompt: `${char}（${hint}）`,
    answer: char,
  })
})

